import {
	type DbmlColumn,
	type DbmlDefault,
	type DbmlEnum,
	type DbmlIndex,
	type DbmlIndexPart,
	type DbmlTable,
	type DbmlTableDetail,
	detailWhen
} from '../model';
import {
	type DrizzleColumn,
	type IndexConfig,
	isSql,
	type PolicyConfig,
	sqlText,
	type TableConfig
} from './dialects';

/*
 * One Drizzle table as a DBML table: its columns with their keys,
 * defaults and generation, its indexes and composite keys, its checks,
 * and what DBML has no syntax for (row-level security, values the app
 * sets, an index's predicate) in notes, so nothing is silently dropped.
 */

const SAFE_MAX = BigInt(Number.MAX_SAFE_INTEGER);
const SAFE_MIN = BigInt(Number.MIN_SAFE_INTEGER);

/* DBML reads a number as a JavaScript one; past the safe range it would
 * lose digits, so a big one is written as an expression. */
const bigintDefault = (value: bigint) => {
	const safe = value <= SAFE_MAX && value >= SAFE_MIN;
	const result: DbmlDefault = safe
		? { kind: 'number', value: `${value}` }
		: { kind: 'expression', value: `${value}` };

	return result;
};

const literalDefault = (value: unknown) => {
	if (value === null) return { kind: 'null' } satisfies DbmlDefault;
	if (typeof value === 'boolean')
		return { kind: 'boolean', value } satisfies DbmlDefault;
	if (typeof value === 'number')
		return { kind: 'number', value } satisfies DbmlDefault;
	if (typeof value === 'bigint') return bigintDefault(value);
	if (typeof value === 'string')
		return { kind: 'string', value } satisfies DbmlDefault;
	if (value instanceof Date)
		return {
			kind: 'string',
			value: value.toISOString()
		} satisfies DbmlDefault;

	return {
		kind: 'string',
		value: JSON.stringify(value)
	} satisfies DbmlDefault;
};

const defaultOf = (column: DrizzleColumn) => {
	if (column.default === undefined) return undefined;
	if (isSql(column.default))
		return {
			kind: 'expression',
			value: sqlText(column.default)
		} satisfies DbmlDefault;

	return literalDefault(column.default);
};

const SERIAL = /Serial/u;

const identityNote = (column: DrizzleColumn) => {
	const type = column.generatedIdentity?.type;
	if (type === 'always') return 'Identity, generated always';
	if (type !== undefined) return 'Identity, generated by default';
	if (column.identity !== undefined) return 'Identity';

	return undefined;
};

const isIncrement = (column: DrizzleColumn) =>
	column.generatedIdentity !== undefined ||
	column.identity !== undefined ||
	column.autoIncrement === true ||
	SERIAL.test(column.columnType);

const generatedText = (value: unknown) => {
	if (isSql(value)) return sqlText(value);
	if (typeof value === 'function') return 'a value the app computes';

	return `${value}`;
};

const generatedNote = (column: DrizzleColumn) => {
	const { generated } = column;
	if (!generated) return undefined;
	const mode = generated.mode ? `, ${generated.mode}` : '';

	return `Generated always as (${generatedText(generated.as)})${mode}`;
};

const present = (lines: (string | undefined)[]) =>
	lines.filter((line): line is string => line !== undefined);

/** Notes for what a column does that DBML has no setting for. */
const columnNotes = (column: DrizzleColumn, storedAs?: string) =>
	present([
		identityNote(column),
		generatedNote(column),
		column.default === undefined && column.defaultFn
			? 'The app sets it when a row is inserted'
			: undefined,
		column.onUpdateFn
			? 'The app sets it whenever the row is updated'
			: undefined,
		column.hasOnUpdateNow === true
			? 'Set to the current time on every update'
			: undefined,
		column.uniqueType === 'not distinct'
			? 'Unique, nulls not distinct'
			: undefined,
		storedAs ? `Stored as ${storedAs}` : undefined
	]);

type ColumnType = {
	enum?: DbmlEnum;
	storedAs?: string;
	type: string;
	typeSchema?: string;
};

const inSchema = (schema: string | undefined) => (schema ? { schema } : {});

/* Drizzle 1.0 counts an array's dimensions; anything that isn't a count
 * is still one array. */
const arraySuffix = (dimensions: number | undefined) => {
	if (dimensions === undefined || dimensions === 0) return '';

	return '[]'.repeat(Number.isFinite(dimensions) ? dimensions : 1);
};

const valuesOf = (values: readonly string[] | undefined) =>
	(values ?? []).map((value) => ({ name: value }));

/* A column's type as DBML shows it. A named enum is its own type; an
 * enum written inline (MySQL's `enum('a','b')`, SQLite text limited to some
 * values) becomes one named for its table and column, so its values show. */
const typeOf = (column: DrizzleColumn, table: TableConfig) => {
	const sqlType = column.getSQLType();
	const arrays = arraySuffix(column.dimensions);
	if (column.enum?.enumName) {
		const named: ColumnType = {
			enum: {
				name: column.enum.enumName,
				...inSchema(column.enum.schema),
				values: valuesOf(column.enumValues)
			},
			type: `${column.enum.enumName}${arrays}`,
			...(column.enum.schema ? { typeSchema: column.enum.schema } : {})
		};

		return named;
	}
	if (!column.enumValues || column.enumValues.length === 0) {
		const plain: ColumnType = { type: `${sqlType}${arrays}` };

		return plain;
	}
	const name = `${table.name}_${column.name}`;
	const inline: ColumnType = {
		enum: {
			name,
			...inSchema(table.schema),
			values: valuesOf(column.enumValues)
		},
		storedAs: sqlType,
		type: name,
		...(table.schema ? { typeSchema: table.schema } : {})
	};

	return inline;
};

const columnOf = (column: DrizzleColumn, table: TableConfig) => {
	const type = typeOf(column, table);
	const notes = columnNotes(column, type.storedAs);
	const fallback = defaultOf(column);
	const result: DbmlColumn = {
		name: column.name,
		type: type.type,
		...(type.typeSchema ? { typeSchema: type.typeSchema } : {}),
		...(column.primary ? { pk: true } : {}),
		...(isIncrement(column) ? { increment: true } : {}),
		...(column.isUnique && !column.primary ? { unique: true } : {}),
		...(column.notNull && !column.primary ? { notNull: true } : {}),
		...(fallback ? { default: fallback } : {}),
		...(notes.length > 0 ? { note: notes.join('\n') } : {})
	};

	return { column: result, enum: type.enum };
};

type IndexedColumnLike = {
	indexConfig?: { nulls?: string; order?: string };
	name: string;
};

const isIndexedColumn = (value: unknown): value is IndexedColumnLike =>
	typeof value === 'object' &&
	value !== null &&
	'name' in value &&
	typeof value.name === 'string';

const partOf = (value: unknown) => {
	if (isSql(value))
		return {
			expression: sqlText(value),
			kind: 'expression'
		} satisfies DbmlIndexPart;
	if (!isIndexedColumn(value))
		return {
			expression: `${value}`,
			kind: 'expression'
		} satisfies DbmlIndexPart;

	return {
		column: value.name,
		kind: 'column',
		...(value.indexConfig?.order === 'desc' ? { desc: true } : {})
	} satisfies DbmlIndexPart;
};

/* An index's nulls ordering, predicate and build options have no DBML
 * setting, so they're said in its note. */
const indexNotes = (config: IndexConfig) => {
	const nulls = config.columns
		.filter(isIndexedColumn)
		.filter((column) => column.indexConfig?.nulls === 'first')
		.map((column) => `${column.name} nulls first`);
	const options = Object.entries(config.with ?? {}).map(
		([key, value]) => `${key} = ${value}`
	);

	return present([
		config.where ? `Where ${sqlText(config.where)}` : undefined,
		nulls.length > 0 ? `Sorted with ${nulls.join(', ')}` : undefined,
		options.length > 0 ? `With ${options.join(', ')}` : undefined,
		config.concurrently === true ? 'Built concurrently' : undefined,
		config.algorithm ? `Algorithm ${config.algorithm}` : undefined,
		config.lock ? `Lock ${config.lock}` : undefined
	]);
};

const methodOf = (config: IndexConfig) => {
	/* Postgres records btree when nothing was chosen; saying so adds
	 * nothing. */
	if (config.method !== undefined)
		return config.method === 'btree' ? undefined : config.method;
	if (config.using === undefined) return undefined;

	return isSql(config.using) ? sqlText(config.using) : config.using;
};

const indexOf = (config: IndexConfig) => {
	const notes = indexNotes(config);
	const method = methodOf(config);
	const index: DbmlIndex = {
		parts: config.columns.map(partOf),
		...(config.unique === true ? { unique: true } : {}),
		...(method ? { type: method } : {}),
		...(config.name ? { name: config.name } : {}),
		...(notes.length > 0 ? { note: notes.join('\n') } : {})
	};

	return index;
};

const roleName = (role: unknown) =>
	typeof role === 'object' && role !== null && 'name' in role
		? `${role.name}`
		: `${role}`;

const roleText = (roles: unknown) =>
	(Array.isArray(roles) ? roles : [roles])
		.filter((role) => role !== undefined)
		.map(roleName)
		.join(', ');

const policyDetail = (policy: PolicyConfig) => {
	const detail: DbmlTableDetail = {
		kind: 'policy',
		name: policy.name,
		text: present([
			policy.as && policy.as !== 'permissive' ? policy.as : undefined,
			`for ${policy.for ?? 'all'}`,
			policy.to === undefined ? undefined : `to ${roleText(policy.to)}`,
			policy.using ? `using (${sqlText(policy.using)})` : undefined,
			policy.withCheck
				? `with check (${sqlText(policy.withCheck)})`
				: undefined
		]).join(' ')
	};

	return detail;
};

const tableDetails = (config: TableConfig) => {
	const policies = config.policies ?? [];
	const secured = config.enableRLS === true || policies.length > 0;
	const details: DbmlTableDetail[] = [
		...detailWhen(secured, { kind: 'row_security' }),
		...policies.map(policyDetail)
	];

	return details.length > 0 ? { details } : {};
};

const columnParts = (columns: readonly DrizzleColumn[]) =>
	columns.map(
		(column) =>
			({ column: column.name, kind: 'column' }) satisfies DbmlIndexPart
	);

const keyIndexes = (config: TableConfig) => [
	...config.primaryKeys.map((key) => {
		const index: DbmlIndex = {
			parts: columnParts(key.columns),
			pk: true,
			...(key.name ? { name: key.name } : {})
		};

		return index;
	}),
	...config.uniqueConstraints.map((constraint) => {
		const index: DbmlIndex = {
			parts: columnParts(constraint.columns),
			unique: true,
			...(constraint.name ? { name: constraint.name } : {}),
			...(constraint.nullsNotDistinct === true
				? { note: 'Nulls not distinct' }
				: {})
		};

		return index;
	})
];

/** One table, and the enums its columns use. */
export const tableOf = (config: TableConfig) => {
	const columns = config.columns.map((column) => columnOf(column, config));
	const table: DbmlTable = {
		checks: config.checks.map((check) => ({
			expression: sqlText(check.value),
			name: check.name
		})),
		columns: columns.map((entry) => entry.column),
		indexes: [
			...keyIndexes(config),
			...config.indexes.map((index) => indexOf(index.config))
		],
		name: config.name,
		...inSchema(config.schema),
		...tableDetails(config)
	};

	return {
		enums: columns
			.map((entry) => entry.enum)
			.filter((entry): entry is DbmlEnum => entry !== undefined),
		table
	};
};

const sortedColumns = (index: DbmlIndex) =>
	index.parts
		.map((part) => (part.kind === 'column' ? part.column : ''))
		.sort()
		.join('\0');

/* A unique index with a predicate is unique only over some rows. */
const coversAll = (index: DbmlIndex) =>
	index.pk === true ||
	(index.unique === true && index.note?.startsWith('Where') !== true);

/** Whether these columns alone are unique in the table: a one-to-one
 *  link rather than many-to-one when they're what a foreign key holds. */
export const isUniqueSet = (table: DbmlTable, columns: string[]) => {
	const [only] = columns;
	const single =
		columns.length === 1
			? table.columns.find((entry) => entry.name === only)
			: undefined;
	if (single?.pk === true || single?.unique === true) return true;
	const wanted = [...columns].sort().join('\0');

	return table.indexes.some(
		(index) =>
			coversAll(index) &&
			index.parts.every((part) => part.kind === 'column') &&
			sortedColumns(index) === wanted
	);
};
