import { describe, expect, test } from 'bun:test';
import { sql } from 'drizzle-orm';
import * as pg from 'drizzle-orm/pg-core';
import { fromDrizzle } from '../src/drizzle';
import { roundTrip } from './roundTrip';

const mood = pg.pgEnum('mood', ['happy', 'sad']);
const auth = pg.pgSchema('auth');
const role = auth.enum('role', ['admin', 'user']);

const users = auth.table(
	'users',
	{
		big: pg.bigint({ mode: 'bigint' }).default(9007199254740993n),
		code: pg.text().unique('users_code_key', { nulls: 'not distinct' }),
		createdAt: pg
			.timestamp('created_at', { withTimezone: true })
			.defaultNow()
			.notNull(),
		data: pg
			.jsonb()
			.$defaultFn(() => ({}))
			.$onUpdate(() => ({})),
		email: pg.varchar({ length: 255 }).notNull().unique(),
		flags: pg.integer().array('[][]'),
		full: pg.text().generatedAlwaysAs(sql`'x'`),
		id: pg.integer().primaryKey().generatedAlwaysAsIdentity(),
		label: pg.text().default("it's"),
		mood: mood().default('happy'),
		nothing: pg.text().default(sql`null`),
		price: pg.numeric({ precision: 10, scale: 2 }),
		ratio: pg.doublePrecision().default(0.5),
		role: role().notNull(),
		seq: pg.integer().generatedByDefaultAsIdentity(),
		settings: pg.jsonb().default({ dark: true }),
		tags: pg
			.text()
			.array()
			.notNull()
			.default(sql`'{}'::text[]`),
		token: pg.uuid().defaultRandom()
	},
	(table) => [
		pg
			.index('users_email_idx')
			.on(table.email.desc().nullsFirst())
			.where(sql`${table.email} is not null`),
		pg.index('users_tags_idx').using('gin', table.tags),
		pg.uniqueIndex().on(sql`lower(${table.email})`),
		pg
			.index('users_brin')
			.using('brin', table.createdAt)
			.with({ pages_per_range: 32 }),
		pg.check('price_pos', sql`${table.price} > ${0}`),
		pg.pgPolicy('own', {
			for: 'select',
			to: 'authenticated',
			using: sql`${table.id} = 1`
		}),
		pg.pgPolicy('admins', {
			as: 'restrictive',
			for: 'all',
			withCheck: sql`true`
		})
	]
);

const posts = pg.pgTable(
	'posts',
	{
		authorId: pg.integer('author_id').references(() => users.id, {
			onDelete: 'cascade',
			onUpdate: 'restrict'
		}),
		id: pg.serial().primaryKey(),
		lang: pg.text(),
		slug: pg.text()
	},
	(table) => [
		pg.unique('slug_lang').on(table.slug, table.lang).nullsNotDistinct()
	]
);

const profiles = pg.pgTable('profiles', {
	bio: pg.text(),
	userId: pg
		.integer('user_id')
		.primaryKey()
		.references(() => users.id)
});

const postTags = pg.pgTable(
	'post_tags',
	{ postId: pg.integer().notNull(), tag: pg.text().notNull() },
	(table) => [
		pg.primaryKey({
			columns: [table.postId, table.tag],
			name: 'post_tags_pk'
		}),
		pg
			.foreignKey({
				columns: [table.postId],
				foreignColumns: [posts.id],
				name: 'post_tags_post'
			})
			.onDelete('set null')
	]
);

const counter = pg.pgSequence('counter', { increment: 2, startWith: 100 });
const admin = pg.pgRole('admin');

const model = fromDrizzle({
	admin,
	auth,
	counter,
	mood,
	posts,
	postTags,
	profiles,
	role,
	users
});
const table = (name: string) =>
	model.tables.find((entry) => entry.name === name);
const column = (tableName: string, name: string) =>
	table(tableName)?.columns.find((entry) => entry.name === name);

describe('Postgres', () => {
	test('reads back from DBML exactly as meant', () => {
		roundTrip(model);
	});

	test('names the database', () => {
		expect(model.project?.databaseType).toBe('PostgreSQL');
	});

	test('enums, from the schema and from a pgSchema, each once', () => {
		expect(
			model.enums.map((entry) => [
				entry.schema,
				entry.name,
				entry.values.map((value) => value.name)
			])
		).toEqual([
			[undefined, 'mood', ['happy', 'sad']],
			['auth', 'role', ['admin', 'user']]
		]);
		expect(column('users', 'role')).toMatchObject({
			notNull: true,
			type: 'role',
			typeSchema: 'auth'
		});
		expect(column('users', 'mood')).toMatchObject({
			default: { kind: 'string', value: 'happy' },
			type: 'mood'
		});
	});

	test('types as Postgres writes them, arrays included', () => {
		expect(column('users', 'email')?.type).toBe('varchar(255)');
		expect(column('users', 'price')?.type).toBe('numeric(10, 2)');
		expect(column('users', 'created_at')?.type).toBe(
			'timestamp with time zone'
		);
		expect(column('users', 'tags')?.type).toBe('text[]');
		expect(column('users', 'flags')?.type).toBe('integer[][]');
	});

	test('keys, identity, serial and uniqueness', () => {
		expect(column('users', 'id')).toMatchObject({
			increment: true,
			note: 'Identity, generated always',
			pk: true
		});
		expect(column('users', 'seq')).toMatchObject({
			increment: true,
			note: 'Identity, generated by default'
		});
		expect(column('posts', 'id')).toMatchObject({
			increment: true,
			pk: true
		});
		expect(column('users', 'email')).toMatchObject({
			notNull: true,
			unique: true
		});
		expect(column('users', 'code')).toMatchObject({
			note: 'Unique, nulls not distinct',
			unique: true
		});
	});

	test('every kind of default', () => {
		expect(column('users', 'created_at')?.default).toEqual({
			kind: 'expression',
			value: 'now()'
		});
		expect(column('users', 'token')?.default).toEqual({
			kind: 'expression',
			value: 'gen_random_uuid()'
		});
		expect(column('users', 'tags')?.default).toEqual({
			kind: 'expression',
			value: "'{}'::text[]"
		});
		expect(column('users', 'label')?.default).toEqual({
			kind: 'string',
			value: "it's"
		});
		expect(column('users', 'ratio')?.default).toEqual({
			kind: 'number',
			value: 0.5
		});
		expect(column('users', 'big')?.default).toEqual({
			kind: 'expression',
			value: '9007199254740993'
		});
		expect(column('users', 'settings')?.default).toEqual({
			kind: 'string',
			value: '{"dark":true}'
		});
		expect(column('users', 'nothing')?.default).toEqual({
			kind: 'expression',
			value: 'null'
		});
	});

	test('what DBML has no setting for is said in a note', () => {
		expect(column('users', 'full')?.note).toBe(
			"Generated always as ('x'), stored"
		);
		expect(column('users', 'data')?.note).toBe(
			'The app sets it when a row is inserted\nThe app sets it whenever the row is updated'
		);
		expect(table('users')?.note).toBe(
			'Row-level security is on\nPolicy own for select to authenticated using ("id" = 1)\nPolicy admins restrictive for all with check (true)'
		);
	});

	test('indexes: order, method, expressions, predicates and options', () => {
		expect(table('users')?.indexes).toEqual([
			{
				name: 'users_email_idx',
				note: 'Where "email" is not null\nSorted with email nulls first',
				parts: [{ column: 'email', desc: true, kind: 'column' }]
			},
			{
				name: 'users_tags_idx',
				parts: [{ column: 'tags', kind: 'column' }],
				type: 'gin'
			},
			{
				parts: [{ expression: 'lower("email")', kind: 'expression' }],
				unique: true
			},
			{
				name: 'users_brin',
				note: 'With pages_per_range = 32',
				parts: [{ column: 'created_at', kind: 'column' }],
				type: 'brin'
			}
		]);
	});

	test('composite keys and named unique constraints', () => {
		expect(table('post_tags')?.indexes[0]).toEqual({
			name: 'post_tags_pk',
			parts: [
				{ column: 'postId', kind: 'column' },
				{ column: 'tag', kind: 'column' }
			],
			pk: true
		});
		expect(table('posts')?.indexes[0]).toMatchObject({
			name: 'slug_lang',
			note: 'Nulls not distinct',
			unique: true
		});
	});

	test('checks, by name, with values written in', () => {
		expect(table('users')?.checks).toEqual([
			{ expression: '"price" > 0', name: 'price_pos' }
		]);
	});

	test('foreign keys: direction, one-to-one, actions and names', () => {
		expect(model.refs).toEqual([
			{
				from: { columns: ['author_id'], table: 'posts' },
				onDelete: 'cascade',
				onUpdate: 'restrict',
				relation: '>',
				to: { columns: ['id'], schema: 'auth', table: 'users' }
			},
			{
				from: { columns: ['postId'], table: 'post_tags' },
				name: 'post_tags_post',
				onDelete: 'set null',
				relation: '>',
				to: { columns: ['id'], table: 'posts' }
			},
			{
				from: { columns: ['user_id'], table: 'profiles' },
				relation: '-',
				to: { columns: ['id'], schema: 'auth', table: 'users' }
			}
		]);
	});

	test('sequences and roles as sticky notes', () => {
		expect(model.notes).toEqual([
			{
				content: 'Sequences\ncounter: increment 2, startWith 100',
				name: 'sequences'
			},
			{ content: 'Roles\nadmin', name: 'roles' }
		]);
	});

	test('groups by schema when asked', () => {
		const grouped = fromDrizzle({ posts, users }, { groups: 'schema' });
		expect(grouped.tableGroups).toEqual([
			{ name: 'public', tables: [{ table: 'posts' }] },
			{ name: 'auth', tables: [{ schema: 'auth', table: 'users' }] }
		]);
		roundTrip(grouped);
	});
});
