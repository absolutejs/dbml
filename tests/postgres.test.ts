import { PGlite } from '@electric-sql/pglite';
import { afterAll, beforeAll, describe, expect, test } from 'bun:test';
import type { DbmlModel } from '../src/model';
import {
	fromPostgres,
	parseDefault,
	type PostgresQuery
} from '../src/postgres';
import { roundTrip } from './roundTrip';

/* A real Postgres (PGlite: Postgres compiled to WebAssembly, in this
 * process), built by hand-written SQL, so the catalogs are read as any
 * database has them rather than as one ORM writes them. */
const SCHEMA = `
create schema billing;
comment on schema billing is 'Money in and out';
create type mood as enum ('happy', 'sad');
create type billing.status as enum ('open', 'paid', 'void');
create sequence invoice_numbers start 1000 increment 10;

create table users (
	id integer generated always as identity primary key,
	email varchar(255) not null unique,
	handle text,
	mood mood default 'happy',
	moods mood[],
	tags text[] not null default '{}',
	created_at timestamptz not null default now(),
	score numeric(10, 2) default 0 check (score >= 0),
	ratio double precision default -1.5,
	big bigint default 9007199254740993,
	active boolean default true,
	nickname text default null,
	label text default 'it''s',
	lower_email text generated always as (lower(email)) stored,
	invited_by integer references users (id) on delete set null
);
comment on table users is 'People who can sign in';
comment on column users.email is 'Where receipts go';
create unique index users_handle_lower on users (lower(handle)) where handle is not null;
create index users_created on users using brin (created_at);
create index users_tags on users using gin (tags);
create index users_score on users (score desc nulls last, id) include (handle);
alter table users enable row level security;
create policy own on users for select to public using (id = 1);

create table billing.invoices (
	id serial primary key,
	number integer not null,
	status billing.status not null default 'open',
	user_id integer not null,
	period daterange,
	constraint invoices_number_unique unique (number),
	constraint invoices_user foreign key (user_id) references users (id) on delete cascade on update restrict deferrable initially deferred,
	constraint invoices_positive check (number > 0)
);

create table profiles (
	user_id integer primary key references users (id),
	bio text
);

create table memberships (
	user_id integer not null references users (id),
	org text not null,
	constraint memberships_pk primary key (user_id, org)
);

create table events (
	id bigint generated by default as identity,
	at timestamptz not null,
	primary key (id, at)
) partition by range (at);
create table events_2026 partition of events for values from ('2026-01-01') to ('2027-01-01');

create view open_invoices as
	select i.id, i.number, u.email from billing.invoices i join users u on u.id = i.user_id where i.status = 'open';
create materialized view user_counts as select mood, count(*) as total from users group by mood;

insert into users (email, handle) values ('a@example.com', 'Ann'), ('b@example.com', null);
`;

let database: PGlite;
let model: DbmlModel;
let query: PostgresQuery;

beforeAll(async () => {
	database = new PGlite();
	await database.exec(SCHEMA);
	query = async (text, params) =>
		(await database.query<Record<string, unknown>>(text, params)).rows;
	model = await fromPostgres(query, { project: { name: 'live' } });
});

afterAll(async () => {
	await database.close();
});

const table = (name: string) =>
	model.tables.find((entry) => entry.name === name);
const column = (tableName: string, name: string) =>
	table(tableName)?.columns.find((entry) => entry.name === name);

describe('a live Postgres database', () => {
	test('reads back from DBML exactly as meant', () => {
		roundTrip(model);
		expect(model.project).toEqual({
			databaseType: 'PostgreSQL',
			name: 'live'
		});
	});

	test('every table, view and partitioned table, partitions folded in', () => {
		expect(
			model.tables.map((entry) => [entry.schema, entry.name]).sort()
		).toEqual(
			[
				['billing', 'invoices'],
				[undefined, 'events'],
				[undefined, 'memberships'],
				[undefined, 'open_invoices'],
				[undefined, 'profiles'],
				[undefined, 'user_counts'],
				[undefined, 'users']
			].sort()
		);
		expect(table('events')?.note).toBe(
			'Partitioned table\nPartitioned by RANGE (at), 1 partitions'
		);
	});

	test('enums in their schemas, and columns typed by them', () => {
		expect(model.enums).toEqual([
			{
				name: 'status',
				schema: 'billing',
				values: [{ name: 'open' }, { name: 'paid' }, { name: 'void' }]
			},
			{ name: 'mood', values: [{ name: 'happy' }, { name: 'sad' }] }
		]);
		expect(column('users', 'mood')).toMatchObject({
			default: { kind: 'string', value: 'happy' },
			type: 'mood'
		});
		expect(column('users', 'moods')?.type).toBe('mood[]');
		expect(
			table('invoices')?.columns.find((entry) => entry.name === 'status')
		).toMatchObject({
			default: { kind: 'string', value: 'open' },
			type: 'status',
			typeSchema: 'billing'
		});
	});

	test('identity, serial, generated columns and comments', () => {
		expect(column('users', 'id')).toMatchObject({
			increment: true,
			note: 'Identity, generated always',
			pk: true
		});
		expect(table('invoices')?.columns[0]).toMatchObject({
			increment: true,
			name: 'id',
			pk: true,
			type: 'integer'
		});
		expect(table('invoices')?.columns[0]?.default).toBeUndefined();
		expect(column('users', 'lower_email')).toMatchObject({
			note: 'Generated always as (lower((email)::text)), stored'
		});
		expect(column('users', 'email')).toMatchObject({
			note: 'Where receipts go',
			notNull: true,
			type: 'character varying(255)',
			unique: true
		});
		expect(table('users')?.note).toBe(
			'People who can sign in\nRow-level security is on\nPolicy own for select to public using (id = 1)'
		);
	});

	test('defaults as literals when they are, expressions when not', () => {
		expect(column('users', 'created_at')?.default).toEqual({
			kind: 'expression',
			value: 'now()'
		});
		expect(column('users', 'tags')?.default).toEqual({
			kind: 'string',
			value: '{}'
		});
		expect(column('users', 'score')?.default).toEqual({
			kind: 'number',
			value: 0
		});
		expect(column('users', 'ratio')?.default).toEqual({
			kind: 'number',
			value: -1.5
		});
		expect(column('users', 'big')?.default).toEqual({
			kind: 'expression',
			value: "'9007199254740993'::bigint"
		});
		expect(column('users', 'active')?.default).toEqual({
			kind: 'boolean',
			value: true
		});
		expect(column('users', 'label')?.default).toEqual({
			kind: 'string',
			value: "it's"
		});
		expect(parseDefault('NULL::text')).toEqual({ kind: 'null' });
		expect(parseDefault("'42'::integer")).toEqual({
			kind: 'number',
			value: 42
		});
		expect(parseDefault("'42'::text")).toEqual({
			kind: 'string',
			value: '42'
		});
		expect(parseDefault('(-1)::integer')).toEqual({
			kind: 'number',
			value: -1
		});
	});

	test('indexes: expressions, methods, order, predicates and included columns', () => {
		expect(table('users')?.indexes).toEqual([
			{
				name: 'users_created',
				parts: [{ column: 'created_at', kind: 'column' }],
				type: 'brin'
			},
			{
				name: 'users_handle_lower',
				note: 'Where handle IS NOT NULL',
				parts: [{ expression: 'lower(handle)', kind: 'expression' }],
				unique: true
			},
			{
				name: 'users_score',
				note: 'Includes handle',
				parts: [
					{ column: 'score', desc: true, kind: 'column' },
					{ column: 'id', kind: 'column' }
				]
			},
			{
				name: 'users_tags',
				parts: [{ column: 'tags', kind: 'column' }],
				type: 'gin'
			}
		]);
	});

	test('keys: composite and named ones keep their names, plain ones sit on the column', () => {
		expect(table('memberships')?.indexes).toEqual([
			{
				name: 'memberships_pk',
				parts: [
					{ column: 'user_id', kind: 'column' },
					{ column: 'org', kind: 'column' }
				],
				pk: true
			}
		]);
		expect(table('invoices')?.indexes).toEqual([
			{
				name: 'invoices_number_unique',
				parts: [{ column: 'number', kind: 'column' }],
				unique: true
			}
		]);
		expect(table('events')?.indexes[0]).toMatchObject({ pk: true });
	});

	test('checks, column and table ones alike', () => {
		expect(table('users')?.checks).toEqual([
			{ expression: 'score >= 0::numeric', name: 'users_score_check' }
		]);
		expect(table('invoices')?.checks).toEqual([
			{ expression: 'number > 0', name: 'invoices_positive' }
		]);
	});

	test('foreign keys: self-references, one-to-one, actions, names and deferral', () => {
		const refs = model.refs.map((ref) => [
			`${ref.from.table}.${ref.from.columns.join()}`,
			ref.relation,
			`${ref.to.table}.${ref.to.columns.join()}`,
			ref.onDelete,
			ref.onUpdate,
			ref.name,
			ref.note
		]);
		expect(refs.sort()).toEqual(
			[
				[
					'invoices.user_id',
					'>',
					'users.id',
					'cascade',
					'restrict',
					'invoices_user',
					'Deferrable, initially deferred'
				],
				[
					'memberships.user_id',
					'>',
					'users.id',
					undefined,
					undefined,
					undefined,
					undefined
				],
				[
					'profiles.user_id',
					'-',
					'users.id',
					undefined,
					undefined,
					undefined,
					undefined
				],
				[
					'users.invited_by',
					'>',
					'users.id',
					'set null',
					undefined,
					undefined,
					undefined
				]
			].sort()
		);
	});

	test('views and materialized views, with lineage from what they read', () => {
		expect(table('open_invoices')?.headerColor).toBe('#64748b');
		expect(
			table('open_invoices')?.note?.startsWith('View:\nSELECT i.id')
		).toBe(true);
		expect(
			table('user_counts')?.note?.startsWith('Materialized view:')
		).toBe(true);
		expect(
			model.deps
				.map(
					(dep) => `${dep.upstream.table} -> ${dep.downstream.table}`
				)
				.sort()
		).toEqual([
			'invoices -> open_invoices',
			'users -> open_invoices',
			'users -> user_counts'
		]);
	});

	test('free-standing sequences and schema comments as sticky notes', () => {
		expect(model.notes).toEqual([
			{
				content: 'Sequences\ninvoice_numbers: start 1000, increment 10',
				name: 'sequences'
			},
			{ content: 'Schemas\nbilling: Money in and out', name: 'schemas' }
		]);
	});

	test('the app’s own schema reads unqualified, and public gets its name', async () => {
		const inBilling = await fromPostgres(query, {
			defaultSchema: 'billing'
		});
		const invoices = inBilling.tables.find(
			(entry) => entry.name === 'invoices'
		);
		expect(invoices?.schema).toBeUndefined();
		expect(
			invoices?.columns.find((entry) => entry.name === 'status')
				?.typeSchema
		).toBeUndefined();
		expect(
			inBilling.tables.find((entry) => entry.name === 'users')?.schema
		).toBe('public');
		expect(
			inBilling.enums.find((entry) => entry.name === 'status')?.schema
		).toBeUndefined();
		expect(
			inBilling.enums.find((entry) => entry.name === 'mood')?.schema
		).toBe('public');
		const ref = inBilling.refs.find(
			(entry) => entry.from.table === 'invoices'
		);
		expect(ref?.from.schema).toBeUndefined();
		expect(ref?.to.schema).toBe('public');
		expect(
			inBilling.notes.find((note) => note.name === 'sequences')?.content
		).toBe('Sequences\npublic.invoice_numbers: start 1000, increment 10');
		roundTrip(inBilling);
	});

	test('first rows as records, when asked', async () => {
		const withRows = await fromPostgres(query, {
			records: { limit: 5 },
			schemas: ['public']
		});
		const users = withRows.records.find(
			(records) => records.table === 'users'
		);
		expect(users?.rows.length).toBe(2);
		expect(users?.rows[0]?.[users.columns.indexOf('email')]).toBe(
			'a@example.com'
		);
		expect(
			withRows.tables.every((entry) => entry.schema === undefined)
		).toBe(true);
		roundTrip(withRows);
	});
});
